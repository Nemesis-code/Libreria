    private void cargarTabla() {
        String[] columnas = {"Título", "Cantidad", "Precio Unitario", "Fecha", "Vendedor"};
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0);

        for (Venta venta : Libreria.ventas) {
            for (LibroVenta lv : venta.librosVendidos) {
                Object[] fila = new Object[5];
                fila[0] = lv.titulo;
                fila[1] = lv.cantidad;
                fila[2] = "Q" + lv.precio;
                fila[3] = venta.fecha.toString();
                fila[4] = venta.usuarioVendedor != null ? venta.usuarioVendedor.nombre : "Desconocido";
                modelo.addRow(fila);
            }
        }

        tablaLibros.setModel(modelo);
    }

