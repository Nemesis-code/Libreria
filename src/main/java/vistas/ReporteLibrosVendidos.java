    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Guardar reporte como CSV");

        int seleccion = fileChooser.showSaveDialog(this);
        if (seleccion == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File archivo = fileChooser.getSelectedFile();

            try (java.io.PrintWriter writer = new java.io.PrintWriter(archivo)) {
                writer.println("Titulo|Cantidad|Precio|Fecha|Vendedor"); // Encabezado

                for (int i = 0; i < tablaLibros.getRowCount(); i++) {
                    String titulo = tablaLibros.getValueAt(i, 0).toString();
                    String cantidad = tablaLibros.getValueAt(i, 1).toString();
                    String precio = tablaLibros.getValueAt(i, 2).toString();
                    String fecha = tablaLibros.getValueAt(i, 3).toString();
                    String vendedor = tablaLibros.getValueAt(i, 4).toString();

                    writer.println(titulo + "|" + cantidad + "|" + precio + "|" + fecha + "|" + vendedor);
                }

                javax.swing.JOptionPane.showMessageDialog(this, "Reporte exportado exitosamente.");
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al exportar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnExportarActionPerformed


